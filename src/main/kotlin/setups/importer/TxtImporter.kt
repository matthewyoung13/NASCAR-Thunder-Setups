package setups.importer

import com.charleskorn.kaml.MultiLineStringStyle
import com.charleskorn.kaml.Yaml
import com.charleskorn.kaml.YamlConfiguration
import setups.load.DataLoader
import setups.model.Setup
import setups.model.SetupFile
import setups.model.Track
import java.nio.file.Path
import kotlin.io.path.*

/**
 * Converter: raw/<game-id>[-<source>].txt -> <out>/setups/<game-id>/<series>[-<source>].yaml plus <out>/REVIEW.md.
 * For example raw/thunder-2003-ign.txt becomes setups/thunder-2003/cup-ign.yaml with `source: ign`.
 *
 * Usage: TxtImporter <rawDir> <outDir>   (data/ is read from <rawDir>/../data)
 */
fun main(args: Array<String>) {
    val rawDir = Path(args.getOrElse(0) { "raw" })
    val outDir = Path(args.getOrElse(1) { "build/import" })
    val dataDir = rawDir.toAbsolutePath().parent / "data"
    val data = DataLoader.load(dataDir)

    val importer = TxtImporter(data.tracks)
    val report = StringBuilder("# Import review\n\nGenerated by `./gradlew importTxt`. Check each item against the YAML before copying it into `data/setups`.\n")

    rawDir.listDirectoryEntries("*.txt").sorted().forEach { file ->
        val name = file.nameWithoutExtension
        // The longest game id the file name starts with; anything after it names the source.
        val gameId = data.games.map { it.id }.filter { name == it || name.startsWith("$it-") }.maxByOrNull { it.length }
        if (gameId == null) {
            report.append("\n## ${file.name}\n\nSkipped: the file name doesn't start with a game id from data/games.yaml.\n")
            println("Skipped ${file.name}: no matching game id")
            return@forEach
        }
        val sourceTag = name.removePrefix(gameId).removePrefix("-").ifEmpty { null }
        val result = importer.import(file.readText())
        result.files.forEach { (series, setups) ->
            val target = outDir / "setups" / gameId / (series + (sourceTag?.let { "-$it" } ?: "") + ".yaml")
            target.createParentDirectories()
            target.writeText(TxtImporter.encode(SetupFile(gameId, series, sourceTag, setups), file.name))
            println("Wrote ${setups.size} setups to $target")
        }
        report.append("\n## ${file.name}\n\n")
        report.append("Setups: ${result.files.values.sumOf { it.size }} (${result.files.entries.joinToString { "${it.key}: ${it.value.size}" }})\n\n")
        if (result.issues.isEmpty()) report.append("No issues.\n")
        result.issues.sortedBy { it.line }.forEach {
            report.append("- line ${it.line}: ${it.message}")
            if (it.context.isNotBlank()) report.append(" — `${it.context.replace("`", "'")}`")
            report.append('\n')
        }
    }
    outDir.createDirectories()
    (outDir / "REVIEW.md").writeText(report.toString())
    println("Review notes: ${outDir / "REVIEW.md"}")
}

class TxtImporter(private val tracks: List<Track>) {

    data class Result(val files: Map<String, List<Setup>>, val issues: List<Issue>)

    /** Heading text (normalised) -> track id. */
    private val trackAliases: Map<String, String> = buildMap {
        tracks.forEach { t ->
            (listOf(t.id, t.name) + t.aliases).forEach { put(TxtParser.normalizeTrackName(it), t.id) }
        }
        // Headings seen in the source text that aren't worth listing as public aliases.
        putAll(
            mapOf(
                "atlanta motorspeedway" to "atlanta",
                "homestead miami" to "homestead",
                "homestead miami (2003)" to "homestead",
                "homestead miami (2002)" to "homestead-2002",
                "lowes motor speedway (charlotte)" to "charlotte",
                "levi stauss signature speedway" to "levi-strauss-speedway",
                "nazereth" to "nazareth",
            )
        )
    }

    private val trackOrder = tracks.withIndex().associate { it.value.id to it.index }

    fun resolveTrack(heading: String): String? = trackAliases[TxtParser.normalizeTrackName(heading)]

    fun import(text: String): Result {
        val parsed = TxtParser(::resolveTrack).parse(text)
        val issues = parsed.issues.toMutableList()

        // Use one spelling per author ("dan312791" / "Dan312791" -> "Dan312791").
        val spellings = parsed.setups.groupBy { it.setup.author.lowercase() }
            .mapValues { (_, list) -> canonicalAuthor(list.map { it.setup.author }) }
        val all = parsed.setups.map { it.copy(setup = it.setup.copy(author = spellings.getValue(it.setup.author.lowercase()))) }

        val kept = mutableListOf<ParsedSetup>()
        for (p in all) {
            val sameAuthor = kept.indexOfFirst {
                it.series == p.series && it.setup.track == p.setup.track && it.setup.author == p.setup.author
            }
            if (sameAuthor >= 0) {
                val prev = kept[sameAuthor]
                when {
                    prev.setup.valuesKey() == p.setup.valuesKey() -> {
                        issues += Issue(p.line, "Exact duplicate of line ${prev.line} removed", "${p.setup.author} @ ${p.setup.track}")
                        continue
                    }
                    sameCore(prev.setup, p.setup) -> {
                        val better = if (score(p.setup) > score(prev.setup)) p else prev
                        kept[sameAuthor] = better
                        issues += Issue(
                            p.line,
                            "Near-duplicate of line ${prev.line} (same core values, some fields differ); kept line ${better.line}. Check both.",
                            "${p.setup.author} @ ${p.setup.track}",
                        )
                        continue
                    }
                }
            }
            // Same values under a different author's name: probably copied. Keep both but flag it.
            kept.firstOrNull {
                it.series == p.series && it.setup.track == p.setup.track &&
                    it.setup.valuesKey().copy(author = "") == p.setup.valuesKey().copy(author = "")
            }?.let {
                issues += Issue(p.line, "Same values as ${it.setup.author}'s setup at line ${it.line}", "${p.setup.author} @ ${p.setup.track}")
            }
            kept += p
        }

        val files = kept.groupBy { it.series }.mapValues { (_, list) ->
            list.sortedWith(compareBy({ trackOrder[it.setup.track] ?: Int.MAX_VALUE }, { it.line })).map { it.setup }
        }
        return Result(files, issues)
    }

    private fun sameCore(a: Setup, b: Setup) =
        a.tirePressure == b.tirePressure && a.frontSprings == b.frontSprings &&
            a.rearSprings == b.rearSprings && a.wedge == b.wedge

    private fun score(s: Setup) = s.usedFields().size + (s.gears?.let { g ->
        (if (g.preset != null) 1 else 0) + (g.ratios?.count { it != null } ?: 0) + (if (g.rearEnd != null) 1 else 0)
    } ?: 0)

    private fun canonicalAuthor(variants: List<String>): String {
        val name = variants.groupingBy { it }.eachCount().entries
            .sortedWith(compareByDescending<Map.Entry<String, Int>> { it.key.first().isUpperCase() }.thenByDescending { it.value })
            .first().key
        return when (name.lowercase().trimEnd('.')) {
            "anonymous" -> "Anonymous"
            else -> name.trimEnd('.', ' ').replaceFirstChar { it.uppercase() }
        }
    }

    companion object {
        private val yaml = Yaml(
            configuration = YamlConfiguration(
                encodeDefaults = false,
                multiLineStringStyle = MultiLineStringStyle.Literal,
                breakScalarsAt = 400,
            )
        )

        fun encode(file: SetupFile, rawName: String = "${file.game}.txt"): String =
            "# ${file.game} / ${file.series}: imported from raw/$rawName\n" +
                yaml.encodeToString(SetupFile.serializer(), file) + "\n"
    }
}
